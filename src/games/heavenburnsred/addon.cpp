constexpr uint32_t ADV_BACKGROUND_PS = 0xA9F8ED91;  // Lily/AdvBackgroundImage
constexpr uint32_t SPRITE_VS = 0xE209A12D;          // shared by Lily/AdvCharacterImage and many UI shaders
constexpr uint32_t ADV_CHARACTER_PS_A = 0xB4EB8715;  // Lily/AdvCharacterImage (+ UI/Default variants)
constexpr uint32_t ADV_CHARACTER_PS_B = 0x85463CFA;

// Per-frame order in story scenes: character parts into their own render textures, the background
// sprite, the character composites, then the PPv2 Uber pass, then the UI canvas. The UI is always
// alpha-blended; the post passes that follow Uber (SMAA, FinalPass, blits) are opaque.
// Story layers over 3D (battles, field) run two Ubers: the 3D camera's, then the story camera's over the
// blitted 3D image, with sprites and atmosphere blended in between. The UI starts after the frame's
// last Uber, taken from the previous frame's count. Reset every present.
std::atomic_bool background_drawn = false;
std::atomic_int uber_count = 0;
std::atomic_int last_frame_uber_count = 1;

bool IsAfterLastUber() {
  const int count = uber_count;
  return count > 0 && count >= last_frame_uber_count;
}

bool IsUberShader(uint32_t pixel_shader_hash) {
  return pixel_shader_hash != ADV_BACKGROUND_PS && custom_shaders.contains(pixel_shader_hash);
}

bool IsBlendEnabled(reshade::api::command_list* cmd_list) {
  auto* context = reinterpret_cast<ID3D11DeviceContext*>(cmd_list->get_native());
  ID3D11BlendState* blend_state = nullptr;
  FLOAT blend_factor[4];
  UINT sample_mask = 0;
  context->OMGetBlendState(&blend_state, blend_factor, &sample_mask);
  if (blend_state == nullptr) return false;
  D3D11_BLEND_DESC desc;
  blend_state->GetDesc(&desc);
  blend_state->Release();
  return desc.RenderTarget[0].BlendEnable != FALSE;
}

uint32_t GetPixelShaderHash(reshade::api::command_list* cmd_list) {
  return renodx::utils::state::GetCurrentShaderHash(cmd_list, reshade::api::pipeline_stage::pixel_shader);
}

// Returns true to skip the draw.
bool OnAnyDraw(reshade::api::command_list* cmd_list) {
  if (cmd_list->get_device()->get_api() != reshade::api::device_api::d3d11) return false;
  const uint32_t pixel_shader_hash = GetPixelShaderHash(cmd_list);
  if (pixel_shader_hash == ADV_BACKGROUND_PS) {
    background_drawn = true;
    return false;
  }
  if (IsUberShader(pixel_shader_hash)) {
    // Runs before mods::shader pushes the injection for this draw.
    shader_injection.custom_uber_chained = (++uber_count >= 2) ? 1.f : 0.f;
    return false;
  }
  if (hide_ui == 0.f || !IsAfterLastUber()) return false;
  return IsBlendEnabled(cmd_list);
}

// The shared sprite VS is replaced only for character composites between the story background and
// post-processing, so they shrink with the zoomed-out background.
bool IsStoryCharacterDraw(reshade::api::command_list* cmd_list) {
  if (shader_injection.custom_background_zoom <= 1.f) return false;
  if (!background_drawn || IsAfterLastUber()) return false;
  const uint32_t pixel_shader_hash = GetPixelShaderHash(cmd_list);
  return pixel_shader_hash == ADV_CHARACTER_PS_A || pixel_shader_hash == ADV_CHARACTER_PS_B;
}

bool OnDraw(reshade::api::command_list* cmd_list, uint32_t, uint32_t, uint32_t, uint32_t) {
  return OnAnyDraw(cmd_list);
}

bool OnDrawIndexed(reshade::api::command_list* cmd_list, uint32_t, uint32_t, uint32_t, int32_t, uint32_t) {
  return OnAnyDraw(cmd_list);
}

void OnPresentResetFrame(reshade::api::command_queue*, reshade::api::swapchain*, const reshade::api::rect*,
                         const reshade::api::rect*, uint32_t, const reshade::api::rect*) {
  background_drawn = false;
  last_frame_uber_count = (uber_count > 0) ? uber_count.load() : 1;
  uber_count = 0;
}

void OnPresentScreenSize(reshade::api::command_queue*, reshade::api::swapchain* swapchain, const reshade::api::rect*,
                         const reshade::api::rect*, uint32_t, const reshade::api::rect*) {
  // URP camera targets render at output size; the background zoom pivots on their center.
  const auto desc = swapchain->get_device()->get_resource_desc(swapchain->get_current_back_buffer());
  shader_injection.custom_screen_width = static_cast<float>(desc.texture.width);
  shader_injection.custom_screen_height = static_cast<float>(desc.texture.height);
}

